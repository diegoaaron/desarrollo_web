-- Fase 4: suscriptores del evento de dominio OrderStatusChanged.
-- event_id es único en ambas tablas: si un evento llegara dos veces, no se duplica nada.

-- Avisos al cliente (campana del header). Los escribe NotificationListener después del commit.
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    order_id BIGINT REFERENCES orders(id) ON DELETE CASCADE,
    title VARCHAR(120) NOT NULL,
    message VARCHAR(500) NOT NULL,
    link VARCHAR(255),
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    read_at TIMESTAMPTZ,
    CONSTRAINT notifications_read_has_date CHECK (NOT is_read OR read_at IS NOT NULL)
);

CREATE INDEX notifications_user_created_idx ON notifications (user_id, created_at DESC);
CREATE INDEX notifications_user_unread_idx ON notifications (user_id) WHERE NOT is_read;
CREATE INDEX notifications_order_id_idx ON notifications (order_id);

-- Bitácora de auditoría genérica (entidad + acción + valores). La escribe AuditListener
-- dentro de la misma transacción del cambio, así que nunca queda un cambio sin auditar.
CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE,
    event_type VARCHAR(60) NOT NULL,
    entity_type VARCHAR(40) NOT NULL,
    entity_id BIGINT NOT NULL,
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    old_value VARCHAR(255),
    new_value VARCHAR(255),
    detail VARCHAR(500),
    occurred_at TIMESTAMPTZ NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX audit_log_entity_idx ON audit_log (entity_type, entity_id, occurred_at);
CREATE INDEX audit_log_actor_id_idx ON audit_log (actor_id);
